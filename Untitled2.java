import java.util.Scanner;
class Squarepattern
{
	public static void main(String[] args) 
	{
       Scanner scan =new Scanner(System.in);
	   int n =Scan.nextint();
	   int i;
	   int j;
		{
			for(i=1;i<=n;i++)
			{
				for(j=1;j<=n;j++)
				{
		System.out.println("*");
	}
        System.out.println("");
}
		}
	}
}
